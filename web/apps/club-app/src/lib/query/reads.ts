export const staleReadsAfter = (changes: readonly DomainChange[]): ReadName[] =>
  READ_NAMES.filter((read) => READ_SHOWS[read].some((shown) => changes.includes(shown)));

export const staleQueryKeysAfter = (changes: readonly DomainChange[]): QueryKey[] =>
  staleReadsAfter(changes).map((read) => READ_ROOTS[read]);

const keyOf = (read: ReadName, ...parts: readonly QueryKeyPart[]): QueryKey => [
  ...READ_ROOTS[read],
  ...parts,
];

